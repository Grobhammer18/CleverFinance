const catalogs: Record<AppLocale, MessageTree> = { de, en };

function getNested(tree: MessageTree, key: string): string | undefined {
  const parts = key.split('.');
  let cur: string | MessageTree | undefined = tree;
  for (const p of parts) {
    if (!cur || typeof cur === 'string') return undefined;
    cur = cur[p];
  }
  return typeof cur === 'string' ? cur : undefined;
}

/** Translation with fallback to German. */
export function t(key: string, locale: AppLocale, vars?: Record<string, string>): string {
  let text = getNested(catalogs[locale], key) ?? getNested(catalogs.de, key) ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
  }
  return text;
}

export function monthLabel(month0: number, locale: AppLocale): string {
  const key = MONTH_KEYS[month0] ?? 'jan';
  return t(`months.${key}`, locale);
}

export function categoryLabel(category: string, locale: AppLocale): string {
  const mapped = CATEGORY_KEY_MAP[category];
  if (!mapped) return category;
  return t(`categories.${mapped}`, locale);
}

export function paymentMethodLabel(method: string, locale: AppLocale): string {
  if (!method) return '';
  const mapped = PAYMENT_METHOD_KEY_MAP[method];
  if (!mapped) return method;
  return t(`paymentMethods.${mapped}`, locale);
}
